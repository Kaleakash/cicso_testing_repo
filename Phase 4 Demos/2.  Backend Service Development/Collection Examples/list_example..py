ll = [1, 2, 3, 4, 5]
print(ll)
ll.append(6)
print(ll)
ll.remove(3) # remove using value 
print(ll)
ll.pop()    # remove last element from the list
print(ll)
ll.insert(2, 10)    # insert 10 at index 2
print(ll)
ll.sort()    # sort the list in ascending order
print(ll)
ll.reverse()    # reverse the list
print(ll)
for item in ll:
    print(item)