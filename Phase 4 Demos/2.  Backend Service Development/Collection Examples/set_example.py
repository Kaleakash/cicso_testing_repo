ss = {"Ravi", "Ankit", "Priya","Rakesh","Ravi","Mahesh"}    # set with initial elements
print(ss)    # print the initial set
ss.add("Suresh")    # add a new element to the set
print(ss)    # print the set after adding a new element
ss.remove("Ankit")    # remove an element from the set
print(ss)    # print the set after removing an element
for item in ss:
    print(item)    # iterate and print each element in the set