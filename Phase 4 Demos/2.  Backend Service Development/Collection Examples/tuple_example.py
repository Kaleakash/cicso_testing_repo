tuple = (1, 2, 3, 4, 5)    # tuple with initial elements
print(tuple)    # print the initial tuple
for item in tuple:
    print(item)    # iterate and print each element in the tuple
print(tuple[0])    # print the first element of the tuple
print(tuple[-1])    # print the last element of the tuple
print(tuple[1:4])    # print a slice of the tuple from index 1 to 3
print(len(tuple))    # print the length of the tuple
print(3 in tuple)    # check if 3 is in the tuple
print(10 in tuple)    # check if 10 is in the tuple 